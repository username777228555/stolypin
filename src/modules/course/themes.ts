export function findThemeById(id: string): CrossTheme | undefined {
  return CROSS_THEMES.find((t) => t.id === id);
}

export function themeLessonIdSet(theme: CrossTheme): Set<string> {
  const set = new Set<string>();
  for (const s of theme.stages) {
    for (const lid of s.lessonIds) set.add(lid);
  }
  return set;
}

export function filterThemes(
  themes: readonly CrossTheme[],
  opts: { category?: ThemeCategory | 'all'; query?: string } = {},
): CrossTheme[] {
  const { category = 'all' } = opts;
  const q = (opts.query ?? '').trim().toLowerCase();

  return themes.filter((t) => {
    if (category !== 'all' && t.category !== category) return false;
    if (!q) return true;
    const hay = [
      t.title,
      t.subtitle,
      t.span,
      t.essayQuestion,
      t.thesisArc,
      ...t.stages.flatMap((s) => [s.title, s.problem, s.solution, s.outcome]),
      ...t.comparePairs.flatMap((c) => [c.title, c.a, c.b]),
      ...t.essayTasks,
    ]
      .join(' ')
      .toLowerCase();
    return hay.includes(q);
  });
}

/**
 * Resolves a CrossTheme against the live knowledge base and user lesson progress,
 * aggregating real dated events, lessons, debates, document projects, pitfalls, persons, terms, and culture.
 */
export function buildThemeBundle(
  theme: CrossTheme,
  data: ThemeDataSource,
  lessonProgress: Readonly<Record<string, LessonState>> = {},
  now = Date.now(),
): ThemeBundle {
  const lessonStageMap = new Map<string, string>();
  const lessonIdSet = new Set<string>();
  const seenEvents = new Set<string>();
  const milestones: ThemeMilestone[] = [];

  for (const stage of theme.stages) {
    for (const lid of stage.lessonIds) {
      lessonIdSet.add(lid);
      if (!lessonStageMap.has(lid)) lessonStageMap.set(lid, stage.title);
    }
    for (const eid of stage.milestoneIds) {
      if (seenEvents.has(eid)) continue;
      const ev = data.eventsById.get(eid);
      if (ev) {
        seenEvents.add(eid);
        milestones.push({ event: ev, stageId: stage.id, stageTitle: stage.title });
      }
    }
  }

  milestones.sort((a, b) => a.event.year - b.event.year || a.event.title.localeCompare(b.event.title, 'ru'));

  const themeLessons = data.lessons.filter((l) => lessonIdSet.has(l.id));
  const lessons: ThemeLessonEntry[] = themeLessons.map((lesson) => {
    const st = lessonProgress[lesson.id];
    const done = Boolean(st?.done);
    const due = isLessonDue(st, now);
    const inProgress = !done && st?.at !== undefined;
    return {
      lesson,
      stageTitle: lessonStageMap.get(lesson.id) ?? '',
      done,
      due,
      inProgress,
    };
  });

  const debates = extractLessonDebates(themeLessons);
  const documents = extractDocumentProjects(themeLessons);

  const pitfalls: ThemePitfall[] = [];
  for (const l of themeLessons) {
    l.sections.forEach((sec, si) => {
      let idx = 0;
      for (const b of sec.blocks ?? []) {
        if (b.type !== 'pitfalls') continue;
        for (const item of b.items) {
          pitfalls.push({
            id: `${l.id}:s${si}:p${idx++}`,
            lessonId: l.id,
            lessonTitle: l.title,
            period: l.period,
            a: item.a,
            b: item.b,
            how: item.how,
          });
        }
      }
    });
  }

  const persons = theme.keyPersons
    .map((id) => data.personsById.get(id))
    .filter((x): x is PersonItem => Boolean(x));

  const terms = theme.keyTerms
    .map((id) => data.termsById.get(id))
    .filter((x): x is TermItem => Boolean(x));

  const culture = theme.keyCulture
    .map((id) => data.cultureById.get(id))
    .filter((x): x is CultureItem => Boolean(x));

  const doneLessons = lessons.filter((l) => l.done).length;
  const totalLessons = lessons.length;

  return {
    theme,
    milestones,
    lessons,
    lessonIdSet,
    debates,
    documents,
    pitfalls,
    persons,
    terms,
    culture,
    stats: {
      doneLessons,
      totalLessons,
      ratio: totalLessons > 0 ? doneLessons / totalLessons : 0,
      milestones: milestones.length,
      documents: documents.length,
      debates: debates.length,
      pitfalls: pitfalls.length,
    },
  };
}

/**
 * Picks up to `count` milestones with strictly distinct years and returns them in shuffled order
 * for the interactive «Хронология линии» ordering drill.
 */
export function createChronologyDrill(
  milestones: readonly ThemeMilestone[],
  count = 4,
  random: () => number = Math.random,
): EventItem[] {
  const byYear = new Map<number, EventItem>();
  for (const m of milestones) {
    if (!byYear.has(m.event.year)) byYear.set(m.event.year, m.event);
  }
  const unique = [...byYear.values()];
  if (unique.length < 2) return unique;

  // Shuffle pool to sample across centuries
  const pool = [...unique];
  for (let i = pool.length - 1; i > 0; i--) {
    const j = Math.floor(random() * (i + 1));
    [pool[i], pool[j]] = [pool[j]!, pool[i]!];
  }
  const picked = pool.slice(0, Math.min(count, pool.length));

  // Ensure the shuffled order isn't already strictly sorted ascending when >2 items
  const sortedIds = [...picked].sort((a, b) => a.year - b.year).map((e) => e.id).join(',');
  if (picked.length > 2 && picked.map((e) => e.id).join(',') === sortedIds) {
    [picked[0], picked[picked.length - 1]] = [picked[picked.length - 1]!, picked[0]!];
  }
  return picked;
}

/** Evaluates the user's chronological order against true event years. */
export function evaluateChronologyDrill(
  orderedIds: readonly string[],
  events: readonly EventItem[],
): ChronologyDrillResult {
  const byId = new Map(events.map((e) => [e.id, e]));
  const correct = [...events].sort((a, b) => a.year - b.year);
  const correctIds = correct.map((e) => e.id);

  let exactMatches = 0;
  for (let i = 0; i < correctIds.length; i++) {
    if (orderedIds[i] === correctIds[i]) exactMatches++;
  }

  // Pairwise order accuracy (Kendall tau style) gives fair partial credit when only 1 item is misplaced
  let pairsTotal = 0;
  let pairsOk = 0;
  for (let i = 0; i < orderedIds.length; i++) {
    for (let j = i + 1; j < orderedIds.length; j++) {
      const a = byId.get(orderedIds[i]!);
      const b = byId.get(orderedIds[j]!);
      if (!a || !b) continue;
      pairsTotal++;
      if (a.year < b.year) pairsOk++;
    }
  }

  const score = pairsTotal > 0 ? Math.round((pairsOk / pairsTotal) * 100) / 100 : 0;
  const allCorrect = exactMatches === correctIds.length && correctIds.length > 0;
  const xp = allCorrect ? 20 : Math.max(6, Math.round(score * 16));

  return {
    correctIds,
    exactMatches,
    total: correctIds.length,
    score,
    xp,
    allCorrect,
  };
}

/** Formats plain summary preview for a theme's pitfall text (strips `[[id|label]]` links). */
export function plainThemeText(text: string): string {
  return stripLessonLinks(text);
}
